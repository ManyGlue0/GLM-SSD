"""Generate IQ quantization lookup tables for Rust and CUDA from ggml's ggml-common.h.

Usage: python -I tools/gen_tables.py ref/llama.cpp/ggml/src/ggml-common.h

The tables are data from ggml (MIT License, Copyright (c) 2023-2026 The ggml authors).
"""
import re
import sys

TABLES = [
    # name, element type, rust type
    ("kmask_iq2xs", "uint8_t", "u8"),
    ("ksigns_iq2xs", "uint8_t", "u8"),
    ("iq2xxs_grid", "uint64_t", "u64"),
    ("iq2s_grid", "uint64_t", "u64"),
    ("iq3xxs_grid", "uint32_t", "u32"),
    ("kvalues_iq4nl", "int8_t", "i8"),
]

HEADER = "Generated by tools/gen_tables.py from ggml/src/ggml-common.h - do not edit.\n" \
         "Table data from ggml (MIT License, Copyright (c) 2023-2026 The ggml authors)."


def parse(src: str, name: str):
    m = re.search(r"GGML_TABLE_BEGIN\(\s*\w+\s*,\s*" + name + r"\s*,\s*(\w+)\s*\)(.*?)GGML_TABLE_END", src, re.S)
    if not m:
        raise SystemExit(f"table {name} not found")
    body = re.sub(r"//[^\n]*", "", m.group(2))
    vals = [int(v, 0) for v in re.findall(r"-?0x[0-9a-fA-F]+|-?\d+", body)]
    return vals


def main():
    src = open(sys.argv[1], encoding="utf-8").read()
    rust = [f"// {l}" for l in HEADER.splitlines()] + ["#![allow(clippy::unreadable_literal)]", ""]
    cuda = [f"// {l}" for l in HEADER.splitlines()] + ["#pragma once", "#include <stdint.h>", ""]
    for name, cty, rty in TABLES:
        vals = parse(src, name)
        fmt = (lambda v: f"0x{v:016x}") if rty == "u64" else (lambda v: f"0x{v:08x}") if rty == "u32" else str
        per = 4 if rty == "u64" else 8 if rty == "u32" else 16
        lines = [", ".join(fmt(v) for v in vals[i:i + per]) for i in range(0, len(vals), per)]
        rust.append(f"pub static {name.upper()}: [{rty}; {len(vals)}] = [")
        rust += [f"    {l}," for l in lines]
        rust += ["];", ""]
        cuda.append(f"static __device__ const {cty} {name}[{len(vals)}] = {{")
        cuda += [f"    {l}," for l in lines]
        cuda += ["};", ""]
        print(f"{name}: {len(vals)} entries")
    open("crates/quants/src/tables.rs", "w", encoding="utf-8", newline="\n").write("\n".join(rust))
    open("crates/cuda/kernels/iq_tables.cuh", "w", encoding="utf-8", newline="\n").write("\n".join(cuda))


if __name__ == "__main__":
    main()
